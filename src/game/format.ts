/**
 * Форматирование чисел для интерфейса.
 *
 * Тысячи разделяются узким пробелом (U+2009), а не обычным: так число на HUD
 * не разъезжается при переносе строки. Дробная часть отбрасывается.
 */
export function fmt(value: number): string {
  return Math.floor(value)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, "\u2009");
}
