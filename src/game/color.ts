/**
 * Цвета: перевод hex в rgba.
 *
 * Крошечная функция, но её вызывают 52 места — от эффектов рамок до боссов.
 * Поведение сохранено дословно: альфа подставляется как есть, без округления,
 * потому что вызывающий код уже передаёт подготовленное число.
 */

export function hexToRgba(hex: string, alpha: number): string {
  const value = parseInt(hex.slice(1), 16);
  return `rgba(${(value >> 16) & 255},${(value >> 8) & 255},${value & 255},${alpha})`;
}
