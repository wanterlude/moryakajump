-- Moryaka Jump — схема глобального рейтинга для Supabase.
-- Выполните этот скрипт в Supabase → SQL Editor → New query → Run.

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  game text not null default 'moryaka-jump',
  name text not null check (char_length(name) between 1 and 20),
  score bigint not null check (score > 0 and score <= 100000000),
  created_at timestamptz not null default now()
);

-- Ускоряет выборку топ-5 по игре.
create index if not exists scores_game_score_idx on public.scores (game, score desc);

-- Row Level Security: анонимный клиент может только читать и добавлять.
alter table public.scores enable row level security;

drop policy if exists "scores read" on public.scores;
create policy "scores read"
  on public.scores for select
  using (true);

drop policy if exists "scores insert" on public.scores;
create policy "scores insert"
  on public.scores for insert
  with check (
    char_length(name) between 1 and 20
    and score > 0 and score <= 100000000
    and game = 'moryaka-jump'
  );

